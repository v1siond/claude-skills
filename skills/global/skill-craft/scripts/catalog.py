#!/usr/bin/env python3
"""Write the skills catalogue from the SKILL.md files themselves, so the list can never drift from the skills.

  catalog.py [--out /home/visiond/projects/claude/skills/SKILLS.md]

For every global/<name>/SKILL.md and specific/<scope>/<name>/SKILL.md under the skills root it prints: the scope
(global, common or the project folder),
what the skill does (the description before "Use when"), the phrases that trigger it (metadata.triggers, the list
the router reads), the repo folders it is scoped to (metadata.root),
what it must not be used for, how it works (its intro and Pipeline, or Target and Procedure), and the scripts it ships.
"""
from __future__ import annotations
import argparse, pathlib, re, yaml

ROOT = pathlib.Path("/home/visiond/projects/claude/skills")
def skill_files(scope: str = "*") -> list[pathlib.Path]:
    """global/<name>/SKILL.md for scope global, specific/<scope>/<name>/SKILL.md for common and each project."""
    found = [] if scope not in ("*", "global") else list(ROOT.glob("global/*/SKILL.md"))
    return sorted(found + ([] if scope == "global" else list(ROOT.glob(f"specific/{scope}/*/SKILL.md"))))


QUOTED = re.compile(r'"([^"]{2,80})"')


def frontmatter(text: str) -> dict:
    return yaml.safe_load(text.split("---", 2)[1]) or {}


def section(body: str, title: str) -> str:
    match = re.search(rf"^## {title}\s*\n(.*?)(?=^## |\Z)", body, re.S | re.M)
    return match.group(1).strip() if match else ""


def split_description(description: str) -> tuple[str, list[str], str]:
    what = re.split(r"\b(Use whenever|Use when|Use on|Use this|Also use)\b", description)[0].strip()
    avoid = description.split("Do NOT use for", 1)[1].strip() if "Do NOT use for" in description else ""
    triggers_part = description.split("Do NOT use for", 1)[0]
    return what, QUOTED.findall(triggers_part), avoid


def entry(path: pathlib.Path) -> str:
    text = path.read_text()
    fields = frontmatter(text)
    body = text.split("---", 2)[2]
    what, quoted, avoid = split_description(fields.get("description", ""))
    meta = fields.get("metadata") or {}
    triggers = meta.get("triggers") or quoted
    root = meta.get("root")
    roots = root if isinstance(root, list) else [root] if root else []
    scripts = sorted(p.name for p in (path.parent / "scripts").glob("*")) if (path.parent / "scripts").is_dir() else []
    lines = [f"### {fields.get('name', path.parent.name)}", "",
             f"**What it does.** {what}", "",
             f"**Triggers.** {', '.join(f'“{t}”' for t in triggers) or 'by its description only'}", ""]
    if roots: lines += [f"**Scoped to.** {', '.join(f'`{r}`' for r in roots)}", ""]
    if avoid: lines += [f"**Not for.** {avoid}", ""]
    # Framework skills (skill-framework.md) have no Target: the intro paragraph before the first section is the goal,
    # and Pipeline is how it works. Skills still in T-I-P-O keep Target and Procedure.
    intro = re.sub(r"His prompts, verbatim.*|^\s*# [^\n]*", "", body.split("\n## ", 1)[0], flags=re.S)
    target = section(body, "Target") or intro.strip()
    procedure = section(body, "Procedure") or section(body, "Pipeline")
    if target: lines += [f"**Goal.** {' '.join(target.split())}", ""]
    if procedure: lines += ["**How it works.**", "", procedure, ""]
    if scripts: lines += [f"**Scripts.** {', '.join(f'`{s}`' for s in scripts)}", ""]
    lines += [f"Source: `{path.parent}` (version {meta.get('version', '?')})", ""]
    return "\n".join(lines)


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--out", default=str(ROOT / "SKILLS.md"))
    out = pathlib.Path(parser.parse_args().out)
    scopes = sorted({p.parent.parent.name for p in skill_files()}, key=lambda s: (s != "global", s != "common", s))
    parts = ["# Skills", "",
             f"Every skill lives in `{ROOT}/global/<name>` (every project) or `{ROOT}/specific/<scope>/<name>`, where scope is",
             "`common` (cross project) or the project folder. Each one is symlinked into `~/.claude/skills`, which is where Claude Code reads them from.",
             "This file is generated by `global/skill-craft/scripts/catalog.py`; edit the skills and run it again.", ""]
    for scope in scopes:
        skills = skill_files(scope)
        parts.append(f"- **{scope}**: {', '.join(p.parent.name for p in skills)}")
    parts.append("")
    for scope in scopes:
        parts += [f"## {scope.capitalize() if scope in ('global', 'common') else 'Project: ' + scope}", ""]
        parts += [entry(p) for p in skill_files(scope)]
    out.write_text("\n".join(parts))
    print(f"{out}: {len(skill_files())} skills")


main()
